#' Rasterize an oriented triangular mesh
#' 
#' `r lifecycle::badge("experimental")`
#' 
#' @description
#' 
#' Creates a binary mask and an optional depth or thickness raster of a
#' specified size by projecting a previously oriented triangular mesh onto the
#' xy plane through triangle rasterization. This is useful for tracing contours,
#' for instance, or as an alternative approach to creating thickness maps.
#' 
#' @details
#' The input mesh x,y coordinates are first translated (internally) so they are
#' centered on the output mask. A scanline algorithm is then employed to test
#' for intersections between lines passing through the centers of the output
#' mask rows and the edges of the mesh triangles (considering only x and y
#' values). Optionally, if `thickness` is set to TRUE, depth is computed either
#' relative to the most distant mesh surfaces, in which case it is equivalent
#' to the mesh thickness at that point, or to a reference Z value that is
#' set through the `ref_z` parameter. Unless you have a good reason to do
#' otherwise, only set the `ref_z` parameter for 2.5D meshes.
#' 
#' @note
#' * Homogeneous coordinates: these are ignored by this function. If using
#' meshes with homogeneous coordinates (4th row of the `mesh.o$vb` matrix) set to
#' something other than 1, please perform the required operations before
#' passing the mesh to this function, as this function simply ignores the 4th
#' row.
#' 
#' @param mesh.o An oriented triangular `mesh3d` object that will be projected
#' onto the XY plane.
#' @param width A positive integer specifying output mask width (nr. columns)
#' @param height A positive integer specifying output mask height (nr. rows)
#' @param padding A positive integer specifying the padding on either side of
#' the mesh; with the default 40x40 resolution, and the default padding of 1,
#' the mesh itself would occupy 38 output cells/pixels.
#' @param thickness A single logical value. If TRUE, thickness or depth will
#' also be computed.
#' @param ref_z A reference Z value for thickness map calculations, or NA. When
#' a value is given, only the maximum Z distance from a mesh surface to the
#' reference Z value will be recorded. This is useful for 2.5D surfaces, but
#' use with care with 3D meshes: 'thickness' will have a different meaning
#' with watertight meshes, and with non-watertight meshes you may get strange
#' values for raster cells where only one surface is visible.
#'
#' @seealso [mesh_tmap()] [mesh_tmap_plot()] [trace_outline()]
#' @examples
#' library(ggplot2)
#' # Generate a binary mask for the demoSphere mesh and plot the result
#' mask <- mesh_rasterize(demoSphere, width=20, height=20,
#'                        padding=1, thickness=FALSE)
#' image(x = mask$centers_x, y = mask$centers_y, z = t(mask$mask),
#'       col = c("white", "black"), breaks = c(-0.5, 0.5, 1.5),
#'       asp = 1, useRaster = TRUE, xlab = "x", ylab = "y")
#'
#' # Generate a depth map for the 2.5D demoSurface mesh relative to a plane
#' # located at Z = -5.
#' # Plot the result.
#' mask <- mesh_rasterize(demoSurface, width=20, height=20, padding=1,
#'                        thickness = TRUE, ref_z = -5)
#' occupied <- which(!is.na(mask$thickness), arr.ind = TRUE)
#' plot_data <- data.frame(xpos = mask$centers_x[occupied[, "col"]],
#'                         ypos = mask$centers_y[occupied[, "row"]],
#'                         thickness = mask$thickness[occupied])
#' ggplot(plot_data, aes(x = xpos, y = ypos, fill = thickness)) +
#'        geom_raster() + coord_fixed()
#'
#' @returns A list with the following elements:
#' 
#' * `mask`: a logical matrix of size `height` * `width` with FALSE (background)
#' or TRUE (mesh hit)
#' * `centers_x`: a vector of X coordinates in the input mesh coordinate system.
#' * `centers_y`: a vector of Y coordinates in the input mesh coordinate system.
#' * `res`: the resolution of the output in mesh units
#' * `ref_z`: an optional (returned if `thickness = TRUE`) reference
#' numeric value, or NA;
#' * `thickness`: an optional (returned if the parameter was set to TRUE)
#' matrix of size `height` * `width` with mesh
#' thickness values (if `ref_z` is set to NA) or distance to the `ref_z`
#' value. Note that NaN values may be generated by triangles perpendicular to
#' the XY plane that happen to cross the exact center of a cell.
#' * `padding`: a scalar corresponding to the input `padding`.
#' 
#' @export
mesh_rasterize <- function(mesh.o, width = 40, height = 40, padding = 1,
                           thickness = TRUE, ref_z = NA) {
  # Validation
  stopifnot(inherits(mesh.o, "mesh3d"))
  stopifnot(length(width) == 1, width > 0, width %% 1 == 0)
  stopifnot(length(height) == 1, height > 0, height %% 1 == 0)
  stopifnot(length(padding) == 1, padding > 0, padding %% 1 == 0)
  stopifnot(2 * padding < min(width, height))
  # Test for single logical here because otherwise the output will silently
  # ignore the thickness parameter due to the isTRUE check, and that
  # may lead to confusion.
  stopifnot(is.logical(thickness), length(thickness) == 1, !is.na(thickness))
  stopifnot(length(ref_z) == 1, is.numeric(ref_z) | is.na(ref_z))
    
  # ------------ Define output raster and center mesh on it ------------- #
  # Prepare mesh data:
  vb <- data.frame(t(mesh.o$vb))[, 1:3]
  it <- t(mesh.o$it)

  # Translate mesh coordinates so they are centered on the output mask  
  mesh_xsize <- diff(range(vb[, 1]))
  mesh_ysize <- diff(range(vb[, 2]))
  res <- max((mesh_xsize / (width - padding * 2)),
             (mesh_ysize / (height - padding * 2)))
  
  # Keep track of shifts in the input.
  x_shift <- (width * res - mesh_xsize) / 2 - min(vb[, 1])
  y_shift <- (height * res - mesh_ysize) / 2 - min(vb[, 2])
  
  # Now translate
  vb[, 1] <- vb[, 1] + (width * res - mesh_xsize) / 2 - min(vb[, 1])
  vb[, 2] <- vb[, 2] + (height * res - mesh_ysize) / 2 - min(vb[, 2])
  
  # Initialize output:
  out <- list()

  # Binary mask
  out$mask <- matrix(FALSE, ncol = width, nrow = height)
  # The centers are not used, but are useful for plotting.
  out$centers_x <- (seq_len(width) - 0.5) * res
  out$centers_y <- (seq_len(height) - 0.5) * res


  # ------------ Pre-compute required data ----------------# 
  # 1. Edge start/end coordinates for all triangles. We will use these
  #    to determine which edges are intersected by the scan lines.
  e1a <- vb[it[, 1], 1:2] # x/y of start, edge 1
  e1b <- vb[it[, 2], 1:2] # x/y of end, edge 1
  e2a <- vb[it[, 2], 1:2] # ...
  e2b <- vb[it[, 3], 1:2]
  e3a <- vb[it[, 3], 1:2]
  e3b <- vb[it[, 1], 1:2]
  
  # 2. Edge dx/dy, for computing x-axis coordinate of the intersection with the
  #    scan lines:
  e1_dxdy <- (e1b[, 1] - e1a[, 1]) / (e1b[, 2] - e1a[, 2])
  e2_dxdy <- (e2b[, 1] - e2a[, 1]) / (e2b[, 2] - e2a[, 2])
  e3_dxdy <- (e3b[, 1] - e3a[, 1]) / (e3b[, 2] - e3a[, 2])
  
  # 3. If thickness is requested
  if (isTRUE(thickness)) {
    # Initiate thickness map
    out$thickness <- matrix(NA_real_, nrow = height, ncol = width)
    out$ref_z <- ref_z
       
    # Compute triangle plane coefficients, required to compute z of
    # intersection points
    normals <- Rvcg::vcgFaceNormals(mesh.o)
    A <- normals[1, ]
    B <- normals[2, ]
    C <- normals[3, ]
    
    p1 <- as.matrix(vb[it[, 1], 1:3])
    D <- -(A * p1[, 1] + B * p1[, 2] + C * p1[, 3])
    
    # Pre-compute z:
    plane_x <- -A / C
    plane_y <- -B / C
    plane_0 <- -D / C
    
    # Pre-allocate scanline buffers:
    z_top <- rep(NA_real_, width)
    z_bottom <- rep(NA_real_, width)
  }

  
  # ------------- Loop through scan lines (centers of rows) ---------------- #
  for(scanline in seq(1, height)) {
    scan_y <- out$centers_y[scanline]
    
    # Reset z buffers if computing thickness
    if (isTRUE(thickness)) {
      z_top[]    <- NA_real_
      z_bottom[] <- NA_real_
    }
    
    # Identify edges that cross the scan line
    #a <- which((e1a[, 2] < out_rast$centers_y[scanline] & e1b[, 2] >= out_rast$centers_y[scanline]) |
    #             (e1b[, 2] < out_rast$centers_y[scanline] & e1a[, 2] >= out_rast$centers_y[scanline]))
    # A XOR equivalent, leaving which for later (more efficient)
    # ymin < scan_y <= ymax
    e1_crosses <- (e1a[, 2] < scan_y) != (e1b[, 2] < scan_y) 
    e2_crosses <- (e2a[, 2] < scan_y) != (e2b[, 2] < scan_y)
    e3_crosses <- (e3a[, 2] < scan_y) != (e3b[, 2] < scan_y)
    
    # Identify candidate triangles
    triangle_idx <- which(e1_crosses | e2_crosses | e3_crosses)
    
    # Check if we have any candidate triangles, otherwise skip:
    if (!length(triangle_idx)) {
      next
    }
    
    # Calculate x of intersection points for every edge:
    x_intersects <- matrix(NA_real_, nrow = length(triangle_idx), ncol = 3)
    
    hit <- e1_crosses[triangle_idx] # Boolean
    hit_idx <- triangle_idx[hit] # Candidate triangles where edge 1 crosses
    x_intersects[hit, 1] <- e1a[hit_idx, 1] + (scan_y - e1a[hit_idx, 2]) * e1_dxdy[hit_idx]
    
    hit <- e2_crosses[triangle_idx] # Boolean
    hit_idx <- triangle_idx[hit] # which are true
    x_intersects[hit, 2] <- e2a[hit_idx, 1] +  (scan_y - e2a[hit_idx, 2]) * e2_dxdy[hit_idx]
    
    hit <- e3_crosses[triangle_idx] # Boolean
    hit_idx <- triangle_idx[hit] # which are true
    x_intersects[hit, 3] <- e3a[hit_idx, 1] +  (scan_y - e3a[hit_idx, 2]) * e3_dxdy[hit_idx]
    
    # 2. Calculate each triangle's leftmost and rightmost x intersection coordinate:
    x_left <- pmin(x_intersects[, 1], x_intersects[, 2], x_intersects[, 3],
                   na.rm = TRUE)
    x_right <- pmax(x_intersects[, 1], x_intersects[, 2], x_intersects[, 3],
                    na.rm = TRUE)
    
    # First and last mask columns occupied by the candidate triangles
    first_col <- as.integer(ceiling(x_left / res + 0.5))
    last_col  <- as.integer(floor(x_right / res + 0.5))
    
    # Identify occupied cells:
    row_mask <- rep(FALSE, width)
    for (cell in which(first_col <= last_col)) {
      row_mask[seq(first_col[cell], last_col[cell])] <- TRUE
    }
    out$mask[scanline, ] <- row_mask

    # If thickness is desired, compute z difference at cell centers
    if(isTRUE(thickness)) {
      keep <- first_col <= last_col # e.g., scanline passing through a vertex
      
      first_col <- first_col[keep]
      last_col  <- last_col[keep]
      span_ids  <- triangle_idx[keep]
      
      # Compute depth for each triangle span:
      for (k in seq_along(span_ids)) {
        triangle <- span_ids[k]
        
        col1 <- first_col[k]
        col2 <- last_col[k]
        cols <- seq.int(col1, col2)
        
        x1 <- (col1 - 0.5) * res
        
        z1 <- plane_x[triangle] * x1 + plane_y[triangle] * scan_y + plane_0[triangle]
        
        dz <- plane_x[triangle] * res
        z  <- z1 + (cols - col1) * dz
        
        z_top[cols] <- pmax(z_top[cols], z, na.rm = TRUE)
        z_bottom[cols] <- pmin(z_bottom[cols], z, na.rm = TRUE)
      }
      
      # Handle reference Z value:
      if (is.na(ref_z)) {
        # If not supplied, calculate the Z-axis range.
        row_thickness <- z_top - z_bottom
      } else {
        # If supplied, compute maximum distance of any intersection from the
        # reference plane/Z value
        row_thickness <- pmax(abs(z_top - ref_z), abs(z_bottom - ref_z))
      }

      out$thickness[scanline, ] <- row_thickness
    } # End if thickness
  } # End scanline loop
  
  #if (isTRUE(center_origin)) {
  #  # To make the output compatible with the existing mesh_tmap function,
  #  # center the raster/mesh on (0,0)
  #  out$centers_x <- out$centers_x - width  * res / 2
  #  out$centers_y <- out$centers_y - height * res / 2
  #}

  out$centers_x <- out$centers_x - x_shift
  out$centers_y <- out$centers_y - y_shift
  
  out$res <- res
  out$padding <- padding
  return(out)
}